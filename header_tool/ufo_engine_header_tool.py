def analyse_scopes(_file_contents_as_list, _scope, _line_number, _currently_searched_directory, _inheritence_map_may_be_null):
    separators = [";"]
    gibberish = ["\n", ";"]

    compound_object = []

    for index in range(len(_file_contents_as_list)):
        item = _file_contents_as_list[index]

        #Most likely if not always a variable
        if item in separators:
            declared_scope = analyse_compound_object(compound_object, _line_number, _currently_searched_directory, _inheritence_map_may_be_null)
            if declared_scope is not None:
                _scope.scopes.append(declared_scope)

            compound_object.clear()

        #Most likely a class or namespace, if not always.
        #If it's just another scope, then analyse the compound object you have so far, and cecurse
        if isinstance(item, list):
            declared_scope = analyse_compound_object(compound_object, _line_number, _currently_searched_directory, _inheritence_map_may_be_null)

            if declared_scope is not None:
                _scope.scopes.append(declared_scope)

                if isinstance(declared_scope, ClassObject):
                    declared_scope.deferred_analyse_scopes_arguments = [item, declared_scope, _line_number, _currently_searched_directory]
                #This else statement might be unnecessary
                else:
                    analyse_scopes(item, declared_scope, _line_number, _currently_searched_directory, _inheritence_map_may_be_null)

            compound_object.clear()
        else:
            if item not in gibberish:
                compound_object.append(item)

        if item == "\n":
            _line_number += 1


