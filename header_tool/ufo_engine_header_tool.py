# This separates a c++ file in segments utilising a few characters as a guide
def separate_with_separators(_file_contents: str) -> list:
    separators = "={}(); ,+-*/%:\n#<>."

    words = []
    word = ""

    inside_string = False

    for i in _file_contents:
        # If stumble upon string-like object

        if inside_string and i != '"':
            word += i

        if i == '"':
            if not inside_string:
                inside_string = True
                word = ""
                words += i
                continue
            else:
                words.append(word)
                words += i
                word = ""
                inside_string = False
                continue

        if inside_string:
            continue

        if i in separators:
            if word != "":
                words.append(word)

            words.append(i)
            word = ""
            continue

        word += i

        if i in separators:
            words.append(word)
            word = ""

    return words


