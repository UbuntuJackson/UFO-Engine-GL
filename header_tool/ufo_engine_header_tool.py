# This function generates the file generated_base_classes.h which should appear in your project root directory of your game
def make_generated_base_classes_file(_path, _classes, _engine_includes):
    pprint.pprint(_classes)

    comment_at_top_of_file = "// generated_base_classes.h\n"
    comment_at_top_of_file+= "//    Do not modify. This file was generated by the UFO-Engine Header Tool to\n"
    comment_at_top_of_file+= "//    support compatability with .ason files which are representative of user\n"
    comment_at_top_of_file+= "//    defined classes.\n\n"

    base_classes_file = "#pragma once\n"
    base_classes_file += _engine_includes + "\n"
    base_classes_file += "namespace ufo::Generated{\n"

    inheritence_map = {}

    for cl in _classes:
        base_class = ""
        class_name = ""

        if len(cl["class"]["extends"]):
            base_class = cl["class"]["extends"][0]

        class_name = cl['class']['name']

        for ufo_macro in cl["macros"]:
            if ufo_macro["name"] == "ufo_actor_config":
                if len(ufo_macro["args"]) != 0:
                    if os.path.exists(_path + "/" + ufo_macro["args"][0]):
                        actor_ason = json.load(open(_path + "/" + ufo_macro["args"][0]))

                        found_Main_actor : bool = False

                        for actor in actor_ason["actors"]:
                            if actor["name"] == "Main":
                                base_class = actor["class_name"]
                                found_Main_actor = True
                                if len(cl["class"]["extends"]):
                                    # Replace class name only if using alias from generated file

                                    if (
                                        "ufo::Generated::"
                                        + cl["class"]["name"]
                                        + "_BaseClass"
                                        == cl["class"]["extends"][0]
                                    ):
                                        cl["class"]["extends"][0] = base_class

                        if not found_Main_actor:
                            cl['errors'].append({'class':cl['class']['name'],'file':ufo_macro["args"][0],'type':"No Actor Named Main"})
                            continue

                        namespace_separated_from_name = class_name.rsplit("::",1)

                        typedef = ""

                        if len(namespace_separated_from_name) == 1:

                            typedef = (
                                "typedef "
                                + " "
                                + base_class
                                + " "
                                + cl["class"]["name"]
                                + "_BaseClass;\n"
                            )
                        else:

                            namespace_name = namespace_separated_from_name[0]
                            class_name_without_namespace = namespace_separated_from_name[1]

                            typedef = (
                                "namespace "+namespace_name+"{\n"
                                "typedef "
                                + " "
                                + base_class
                                + " "
                                + class_name_without_namespace
                                + "_BaseClass;\n"
                                + "}\n"
                            )

                        base_classes_file += typedef

        inheritence_map[cl["class"]["name"]] = base_class

    base_classes_file += "}\n"

    base_classes_file = comment_at_top_of_file + base_classes_file

    f = open(_path + "/generated_base_classes.h", "w")
    f.write(base_classes_file)
    f.close()

    return inheritence_map

# This function generates the file generated.h which should appear in your project root directory of your game
def make_generated_file(_path, _classes, _engine_includes, _structured_classes_dict, _inheritence_map):
    comment_at_top_of_file = "// generated.h\n"
    comment_at_top_of_file+= "//    Do not modify. This file was generated by the UFO-Engine Header Tool to\n"
    comment_at_top_of_file+= "//    support creation of various user defined C++ classes.\n\n"

    includes = _engine_includes

    header_files = []

    for cl in _classes:
        if cl["class"]["header_file"] not in header_files:
            header_files.append(cl["class"]["header_file"])

    for i in header_files:
        includes += '#include "' + i + '"\n'

    includes += "\n"

    includes+="#include <stdexcept>\n"

    namespace_string = "namespace ufo::Generated{\n\n"

    namespace_string += generate_actor_spawner_functions.main(_path, _structured_classes_dict, _inheritence_map)

    class_string = "class ActorGenerator : public ufo::GenericGenerator{\n\n"
    class_string += "    public:\n"

    class_string += "    std::unique_ptr<Actor> FromJson(ufo::gc::JsonMap* _json){return std::move(FromJsonInGame(_json));}\n"

    # Parent class has the generator_map now.
    # generator_map = "    std::map<std::string, std::function<std::unique_ptr<Actor>(ufo::gc::JsonMap* _json)>> factory_map;\n"

    function_ = "    void Initialise(ufo::Engine* _engine){\n"
    function_ += "        GenericGenerator::Initialise(_engine);\n"

    for cl in _classes:
        function_ += "        runtime_factory_map.emplace(\n"
        function_ += (
            '            "'
            + cl["class"]["name"]
            + '",\n'
            + "            [](Vector2f _local_position){\n"
        )

        function_ += (
            "                auto instance = std::make_unique<"
            + "::" + cl["class"]["name"]
            + ">(_local_position);\n"
        )

        function_ += "                return std::move(instance);\n"

        function_ += "            }\n        );\n"

    for cl in _classes:
        function_ += "        factory_map.emplace(\n"

        function_ += (
            '            "'
            + cl["class"]["name"]
            + '",\n'
            + "            [](ufo::gc::JsonMap* _json){\n"
        )

        function_ += '                float _x = _json->map.at("x")->AsFloat();\n'
        function_ += '                float _y = _json->map.at("y")->AsFloat();\n'

        function_ += (
            "                auto instance = std::make_unique<"
            + "::" + cl["class"]["name"]
            + ">(Vector2f(_x, _y));\n"
        )

        function_ += '                auto custom_properties = _json->map.at("custom_editor_properties")->AsMap();\n'

        for member in cl["class"]["members"]:

            member_variable_name = member[1]["name"]
            member_variable_data_type = member[1]["data_type"]

            function_ += "                try{\n"
            function_ += "                    instance->"

            if member_variable_data_type == "int":
                function_ += (
                    member_variable_name
                    + ' = (int)(custom_properties.at("'
                    + member_variable_name
                    + '")->AsMap().at("value")->AsFloat());\n'
                )
            if member_variable_data_type == "float":
                function_ += (
                    member_variable_name
                    + ' = (custom_properties.at("'
                    + member_variable_name
                    + '")->AsMap().at("value")->AsFloat());\n'
                )
            if member_variable_data_type == "bool":
                function_ += (
                    member_variable_name
                    + ' = (bool)(custom_properties.at("'
                    + member_variable_name
                    + '")->AsMap().at("value")->AsFloat());\n'
                )
            if member_variable_data_type == "Vector2f":
                pass
            if member_variable_data_type == "std::string":
                function_ += (
                    member_variable_name
                    + ' = custom_properties.at("'
                    + member_variable_name
                    + '")->AsMap().at("value")->AsString();\n'
                )

            function_ += '                } catch(const std::out_of_range& _error){\n'
            function_ += '                    if(!custom_properties.count("'+ member_variable_name + '")) Console::PrintLine("[UFO-Engine] Generated::ActorGenerator:", _error.what(),"Error trying to get key \''+member_variable_name+'\' inside \'custom_properties\' for variable '+member_variable_name+' in instance of class '+cl["class"]["name"]+'");\n'
            function_ += '                    else if(!custom_properties.at("'+ member_variable_name + '")->AsMap().count("value")) Console::PrintLine("[UFO-Engine] Generated::ActorGenerator:", _error.what(),"Error trying to get key \'value\' inside \'custom_properties\' for variable '+member_variable_name+' in instance of class '+cl["class"]["name"]+'");\n'
            function_ += "                }\n"

        function_ += "                return std::move(instance);\n"

        function_ += "            }\n        );\n"

    function_ += "    }\n"

    # This functionality is now done in parent class
    # function_ += "    std::unique_ptr<Actor> FromJson(ufo::gc::JsonMap* _json){return std::move(factory_map.at(_json->map.at(\"name\")->AsString())(_json));}"

    function_ += "};\n\n"

    function_ += "}\n"

    f = open(_path + "/generated.h", "w")
    f.write(comment_at_top_of_file+includes + namespace_string + class_string + function_)
    f.close()


