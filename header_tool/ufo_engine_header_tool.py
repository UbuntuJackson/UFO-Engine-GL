def analyse_class_or_variable(_object):
    def extract_string(_list):
        if len(_list) > 3:
            ufo_header_tool_log.ufo_header_tool_print(
                "[UFO Header Tool Warning] Parsing error, string",
                _object,
                "contains more than 3 elements",
            )
        elif len(_list) < 2:
            ufo_header_tool_log.ufo_header_tool_print(
                "[UFO Header Tool Warning] Parsing error, string",
                _object,
                "less than 2 elements",
            )
        else:
            if _list[0] == '"' and _list[-1] == '"':
                if len(_list) == 2:
                    return ""
                if len(_list) == 3:
                    return _list[1]

            else:
                ufo_header_tool_log.ufo_header_tool_print("[UFO Header Tool Warning] Parsing error, odd tokens:", _object)

        return ""

    def extract_int(_list):
        if len(_list) == 0:
            return "0"
        elif len(_list) == 1:
            if not _list[0].isnumeric():
                ufo_header_tool_log.ufo_header_tool_print(
                    "[UFO Header Tool Warning] Parsing error, parameter has to be numeric",
                    _list,
                )
            else:
                return _list[0]
        elif len(_list) == 2:
            if _list[0] != "-":
                ufo_header_tool_log.ufo_header_tool_print("[UFO Header Tool Warning] Parsing error, weird prefix", _list)
            else:
                if not _list[1].isnumeric():
                    ufo_header_tool_log.ufo_header_tool_print(
                        "[UFO Header Tool Warning] Parsing error, second parameter has to be numeric",
                        _list,
                    )
                else:
                    return _list[0] + _list[1]
        elif len(_list) > 2:
            ufo_header_tool_log.ufo_header_tool_print(
                "[UFO Header Tool Warning] Parsing error, int can't be more than two elements",
                _list,
            )
        return "0"

    def extract_bool(_list):
        if len(_list) == 1:
            if _list[0] == "true":
                return "1"
            elif _list[0] == "false":
                return "0"
            else:
                ufo_header_tool_log.ufo_header_tool_print(
                    "[UFO Header Tool Warning] Parsing error, parameter has to be boolean litteral"
                )
        else:
            ufo_header_tool_log.ufo_header_tool_print(
                "[UFO Header Tool Warning] Parsing error, parameter has to be single litteral"
            )

    def extract_float(_list):
        if len(_list) == 0:
            return "0.0"
        elif len(_list) == 1:
            if not is_float_litteral(_list[0]):
                ufo_header_tool_log.ufo_header_tool_print(
                    "[UFO Header Tool Warning] Parsing error, parameter has to be float litteral",
                    _list,
                )
            else:
                return _list[0][:-1]
        elif len(_list) == 2:
            if _list[0] != "-":
                ufo_header_tool_log.ufo_header_tool_print("[UFO Header Tool Warning] Parsing error, weird prefix", _list)
            else:
                if not is_float_litteral(_list[1]):
                    ufo_header_tool_log.ufo_header_tool_print(
                        "[UFO Header Tool Warning] Parsing error, second parameter has to be float litteral",
                        _list,
                    )
                else:
                    return _list[0] + _list[1][:-1]
        elif len(_list) > 2:
            ufo_header_tool_log.ufo_header_tool_print(
                "[UFO Header Tool Warning] Parsing error, int can't be more than two elements",
                _list,
            )
        return "0.0"

    def extract_colour(_list):
        colour = []

        for i in _list:
            if i.isnumeric():
                colour.append(i)

        if len(colour) < 3:
            return [0, 0, 0, 0]
        if len(colour) == 3:
            return colour + [255]

        return colour

    def extract_vector2f(_list):
        vec = []

        vector_syntax_confirmed = False
        open_parantheses = False
        close_parantheses = False
        parantheses_syntax_confirmed = False

        arg = ""

        for i in _list:
            if i == "Vector2f":
                vector_syntax_confirmed = True
            if i == "(":
                open_parantheses = True
            if i == ")":
                close_parantheses = True
                vec.append(extract_float(arg))
            if i not in ["Vector2f", "(", ")", ","]:
                arg += i

            if i == ",":
                vec.append(extract_float(arg))
                arg = ""

        parantheses_syntax_confirmed = open_parantheses and close_parantheses

        if not parantheses_syntax_confirmed:
            ufo_header_tool_log.ufo_header_tool_print("[UFO Header Tool Warning] Parantheses syntax not confirmed")
        if not vector_syntax_confirmed:
            ufo_header_tool_log.ufo_header_tool_print("[UFO Header Tool Warning] Vector syntax not confirmed")

        if len(vec) < 2:
            ufo_header_tool_log.ufo_header_tool_print(
                "[UFO Header Tool Warning] Parsing error, only one default value provided",
                _list,
            )
            return ["0.0", "0.0"]

        return vec

    if _object[0] == "class":
        ufo_class_name = ""
        inheritence = False
        inherits_from_classes = []

        for index in range(1, len(_object)):
            item = _object[index]

            if item == ":":
                inheritence = True
                inherits_from_classes.append("")
            else:
                if not inheritence:
                    ufo_class_name += item
                else:
                    if item == ",":
                        inherits_from_classes.append("")
                    else:
                        if item != "public":
                            inherits_from_classes[-1] += item

        return ClassObject(ufo_class_name, inherits_from_classes)
    else:
        data_type = ""
        name = ""
        value = []
        for index in range(0, len(_object)):
            item = _object[index]
            if item == "=":
                continue
            next_item = None
            # If there still is a next item
            if index + 1 < len(_object):
                next_item = _object[index + 1]
            # If there is no default value
            elif "=" not in _object:
                name = item
                break

            if next_item == "=":
                name = item
                continue

            if name == "":
                data_type += item

            if name != "" and data_type != "":
                value.append(item)

        if data_type == "std::string":
            value = extract_string(value)
        elif data_type == "int":
            value = extract_int(value)
        elif data_type == "bool":
            value = extract_bool(value)
        elif data_type == "float":
            value = extract_float(value)
        elif data_type == "Vector2f":
            value = extract_vector2f(value)
        elif data_type == "ufo::Colour":
            value = extract_colour(value)
        else:
            ufo_header_tool_log.ufo_header_tool_print(
                "[UFO Header Tool Warning] Error, unknown datatype: '" + data_type + "'"
            )
            return VariableObject("std::string", name, "")

        return VariableObject(data_type, name, value)

    return None


def analyse_nested_angled_brackets(_list):
    local_list = []

    within_angled_brackets = []

    angled_bracket_count = 0

    for item in _list:

        if angled_bracket_count == 0:
            if item not in ['<','>']:
                local_list.append(item)
        else:
            within_angled_brackets.append(item)

        if item == '<':
            angled_bracket_count+=1
            #analyse_nested_angled_brackets()
        if item == '>':
            angled_bracket_count-=1
            if angled_bracket_count == 0:
                local_list.append(analyse_nested_angled_brackets(copy.deepcopy(within_angled_brackets)))
                within_angled_brackets.clear()

    return local_list

