def search_folders_for_ufo_classes(
    _grand_class_list, _working_directory, _local_path, _grand_header_tool_log
):
    for directory in os.listdir(_working_directory + _local_path):
        # Don't go into the engine or build folder, that could be nasty
        if directory in ["UFO-Engine", "UFO-Engine-GL", "build"]:
            continue

        # If directory, recurse further
        if os.path.isdir(_working_directory + "/" + _local_path + "/" + directory):
            search_folders_for_ufo_classes(
                _grand_class_list,
                _working_directory,
                _local_path + "/" + directory,
                _grand_header_tool_log,
            )

        if os.path.isfile(_working_directory + "/" + _local_path + "/" + directory):
            extension = directory[directory.find(".") : len(directory)]

            if extension in [".ufo.hpp", ".ufo.h"]:
                file_to_parse = _working_directory + "/" + _local_path + "/" + directory
                ufo_header_tool_log.ufo_header_tool_print("[UFO-Header Tool] Parsing file", file_to_parse)
                local_classes, header_tool_log_for_file = search_file(
                    file_to_parse,
                    _local_path,
                    directory # Not a directory here but a file.
                )
                _grand_header_tool_log.obj += (
                    "Hierarchal scope structure of " + file_to_parse
                )
                _grand_header_tool_log.obj += header_tool_log_for_file + "\n"
                _grand_class_list.append(local_classes)


def search_file(_path, _local_path, _file_name):
    f = open(_path)

    print("File in directory",_local_path)

    file_contents = f.read()

    # Divide code with separators to make it a bit easier to parse
    segmented_file_contents = separate_with_separators(file_contents)

    # Some colons are supposed to be attached to eachother, like std::string or ufo::PlatformerCollision
    segmented_file_contents_cleaned = clean_up_colons(segmented_file_contents)

    # Since comments can be confused for separators, the comment syntax // and /* */ should be made into their dedicated strings
    segmented_file_contents_cleaned_up_multi_line_comments = (
        clean_up_multi_line_comments(segmented_file_contents_cleaned)
    )

    # Since comments can be confused for separators, the comment syntax // and /* */ should be made into their dedicated strings
    segmented_file_contents_cleaned_up_single_line_comments = (
        clean_up_single_line_comments(
            segmented_file_contents_cleaned_up_multi_line_comments
        )
    )

    #Here the comments are actually filtered out
    segmented_file_contents_single_line_comments_processed = (
        get_contents_without_single_line_comments(
            segmented_file_contents_cleaned_up_single_line_comments
        )
    )

    segmented_file_contents_multi_line_comments_processed = (
        get_contents_without_multi_line_comments(
            segmented_file_contents_single_line_comments_processed
        )
    )

    # Since floating point numbers contain separators, these need to be concatenated into dedicated strings
    segmented_file_contents_cleaned_up_floating_point_numbers = (
        clean_up_floating_point_numbers(
            segmented_file_contents_multi_line_comments_processed
        )
    )

    # We don't need spaces anymore, remove them.
    space_less_file_contents = remove_spaces(
        segmented_file_contents_cleaned_up_floating_point_numbers
    )

    f.close()

    #The contents are converted into a recursive list, each array representing a scope
    scopes = detect_scopes(space_less_file_contents, 0)

    header_tool_file_log = pprint.pformat(scopes, indent=4)

    global_scope = GlobalScope()
    global_scope.local_path = _local_path
    global_scope.file_name = _file_name

    analyse_scopes(scopes, global_scope, 1, _local_path, None)

    return (global_scope, header_tool_file_log)


def get_contents_without_multi_line_comments(_file_contents_as_list):
    contents_without_comments = []

    inside_multi_line_comment = False

    for item in _file_contents_as_list:
        if not inside_multi_line_comment:
            if item == "/*":
                inside_multi_line_comment = True
                continue

        else:
            if item == "*/":
                inside_multi_line_comment = False
            continue

        contents_without_comments.append(item)

    return contents_without_comments


def get_contents_without_single_line_comments(_file_contents_as_list):
    contents_without_comments = []

    inside_single_line_comment = False

    for item in _file_contents_as_list:
        if not inside_single_line_comment:
            if item == "//":
                inside_single_line_comment = True
                continue

        else:
            if item == "\n":
                inside_single_line_comment = False
            continue

        contents_without_comments.append(item)

    return contents_without_comments


def detect_includes(_file_contents_as_clean_list):
    includes = []

    for index in range(len(_file_contents_as_clean_list)):
        item = _file_contents_as_clean_list[index]

        if item == "#":
            if not (index + 1 >= len(_file_contents_as_clean_list)):
                if _file_contents_as_clean_list[index + 1] == "include":
                    if not (index + 3 >= len(_file_contents_as_clean_list)):
                        # Taking a shortcut here checking directly for middle item
                        if _file_contents_as_clean_list[index + 3] != '"':
                            includes.append(_file_contents_as_clean_list[index + 3])

    return includes


def detect_scopes(_file_contents_as_clean_list, _depth):
    squiggly_bracket_count = 0

    complete_scope = []
    scope_contents_temp = []

    for i in _file_contents_as_clean_list:
        if i == "{":
            should_continue = False
            if squiggly_bracket_count == 0:
                # ufo_header_tool_log.ufo_header_tool_print(_depth * "    " + "Scope start")
                should_continue = True

            squiggly_bracket_count += 1
            if should_continue:
                continue

        if i == "}":
            squiggly_bracket_count -= 1
            if squiggly_bracket_count == 0:
                # for j in scope_contents:
                #    ufo_header_tool_log.ufo_header_tool_print(_depth * "    " + "'" + j + "'")
                complete_scope.append(detect_scopes(scope_contents_temp, _depth + 1))

                # ufo_header_tool_log.ufo_header_tool_print(_depth * "    " + "Scope end")
                scope_contents_temp.clear()
                continue

        if squiggly_bracket_count != 0:
            scope_contents_temp.append(i)
        else:
            complete_scope.append(i)
            # ufo_header_tool_log.ufo_header_tool_print(_depth * "    " + "deep content '" + i + "'")

    return complete_scope


